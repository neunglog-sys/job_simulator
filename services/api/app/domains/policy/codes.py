def ctpv_aliases(name: str | None) -> tuple[str, ...]:
    """같은 지역을 가리키는 표기들. 통합/개칭된 시도를 한 덩어리로 본다."""
    target = (name or "").strip()
    if not target:
        return ()
    for group in CTPV_EQUIVALENTS:
        if target in group:
            return group
    return (target,)

